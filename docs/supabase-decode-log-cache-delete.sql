-- CarDNA — the server side of the free tier, the VIN cache, and account deletion (Turn 36)
--
-- Covers three registry items that belong together because they all need the database to be the
-- authority rather than the browser:
--
--   F-26  a real decode count, so clearing site data no longer resets a Free plan's three decodes
--   F-27  the VIN cache, so a repeat decode costs nothing and a report can render without NHTSA
--   F-25  self-serve deletion, with a hard refusal for the owner account
--
-- Idempotent: safe to run twice. Run it in Supabase -> SQL Editor. Nothing is emailed and no data
-- leaves Supabase. The browser modules are wired to these names; until the file is run they answer
-- honestly that the service is missing.

begin;

-- 1. F-27 — the VIN cache ----------------------------------------------------------------------
-- Public NHTSA data, so it is readable by anyone; only a signed-in account may fill it in, and
-- only with a real 17-character VIN.
--
-- Correction (Turn 40): this table already existed in the project with a `payload` column, and
-- `create table if not exists` therefore changed nothing. The live shape — and the shape the
-- browser modules read and write — is: vin, payload, source (default 'vincario'), fetched_at.
-- There is no `fields` column and no `hits` column; the block below now states the shape that is
-- actually in the database, so a fresh project and this one agree.

create table if not exists public.decode_cache (
  vin        text not null,
  payload    jsonb not null,
  source     text not null default 'vincario',
  fetched_at timestamptz not null default now(),
  constraint decode_cache_pkey primary key (vin),
  constraint decode_cache_vin_format check (vin ~ '^[A-HJ-NPR-Z0-9]{17}$')
);

alter table public.decode_cache enable row level security;

drop policy if exists decode_cache_read on public.decode_cache;
create policy decode_cache_read on public.decode_cache
  for select to anon, authenticated
  using (true);

drop policy if exists decode_cache_insert on public.decode_cache;
create policy decode_cache_insert on public.decode_cache
  for insert to authenticated
  with check (char_length(vin) = 17);

drop policy if exists decode_cache_update on public.decode_cache;
create policy decode_cache_update on public.decode_cache
  for update to authenticated
  using (true)
  with check (char_length(vin) = 17);

grant select on public.decode_cache to anon, authenticated;
grant insert, update on public.decode_cache to authenticated;

-- 2. F-26 — the decode log ---------------------------------------------------------------------
-- One row per account per VIN: decoding the same car twice is not two decodes.

create table if not exists public.decode_log (
  id         bigint generated by default as identity primary key,
  user_id    uuid not null default auth.uid(),
  vin        text not null,
  created_at timestamptz not null default now(),
  constraint decode_log_vin_len check (char_length(vin) = 17)
);

create index if not exists decode_log_user_idx on public.decode_log (user_id, created_at desc);
create unique index if not exists decode_log_user_vin_idx on public.decode_log (user_id, vin);

alter table public.decode_log enable row level security;

-- Read your own log. Rows are only ever written by cardna_record_decode below, never by the client.
drop policy if exists decode_log_read_own on public.decode_log;
create policy decode_log_read_own on public.decode_log
  for select to authenticated
  using (user_id = auth.uid());

grant select on public.decode_log to authenticated;
grant usage, select on sequence public.decode_log_id_seq to authenticated;

-- The cap per plan. Mirrors PLAN_LIMITS in assets/auth.js: free 3, paid plans unlimited (0).
create or replace function public.cardna_decode_limit(plan_name text)
returns integer
language sql immutable
as $$
  select case lower(coalesce(plan_name, 'free'))
    when 'free' then 3
    when 'pro' then 0
    when 'workshop' then 0
    when 'business' then 0
    else 3
  end;
$$;

-- Who this account is, what it may decode, and what it has left.
create or replace function public.cardna_decode_usage()
returns jsonb
language plpgsql security definer set search_path = public
as $$
declare
  uid       uuid := auth.uid();
  plan_name text;
  cap       integer;
  used      integer;
begin
  if uid is null then
    return jsonb_build_object('limited', true, 'limit', 3, 'used', 0, 'left', 3);
  end if;

  /* Staff are not on a plan: no cap at all. */
  if exists (select 1 from public.profiles p where p.id = uid and lower(coalesce(p.role, '')) in ('owner', 'admin')) then
    return jsonb_build_object('limited', false, 'limit', 0, 'used', 0, 'left', 0);
  end if;

  select lower(coalesce(p.plan, 'free')) into plan_name from public.profiles p where p.id = uid;
  plan_name := coalesce(plan_name, 'free');
  cap := public.cardna_decode_limit(plan_name);

  select count(*) into used from public.decode_log l where l.user_id = uid;

  return jsonb_build_object(
    'limited', cap > 0,
    'limit', cap,
    'used', used,
    'left', case when cap > 0 then greatest(cap - used, 0) else 0 end
  );
end;
$$;

-- Record one decode. Refuses when the plan is spent, so the limit is a rule, not a counter.
create or replace function public.cardna_record_decode(vin text)
returns jsonb
language plpgsql security definer set search_path = public
as $$
declare
  uid     uuid := auth.uid();
  usage   jsonb;
  already boolean;
  clean   text;
begin
  if uid is null then
    return jsonb_build_object('ok', false, 'error', 'Not signed in.');
  end if;

  clean := upper(trim(coalesce(vin, '')));
  if char_length(clean) <> 17 then
    return jsonb_build_object('ok', false, 'error', 'A VIN is 17 characters.');
  end if;

  usage := public.cardna_decode_usage();

  select exists (
    select 1 from public.decode_log l where l.user_id = uid and l.vin = clean
  ) into already;

  if already then
    return jsonb_build_object('ok', true, 'repeat', true, 'usage', usage);
  end if;

  if (usage->>'limited')::boolean and (usage->>'left')::int <= 0 then
    return jsonb_build_object('ok', false, 'error', 'decode limit reached', 'usage', usage);
  end if;

  insert into public.decode_log (user_id, vin) values (uid, clean)
  on conflict (user_id, vin) do nothing;

  return jsonb_build_object('ok', true, 'repeat', false, 'usage', public.cardna_decode_usage());
end;
$$;

grant execute on function public.cardna_decode_limit(text) to authenticated;
grant execute on function public.cardna_decode_usage() to authenticated;
grant execute on function public.cardna_record_decode(text) to authenticated;

-- 3. F-25 — delete my own account ---------------------------------------------------------------
-- Deletes the caller's profile, saved vehicles, vault rows, activity, decode log, waitlist rows and
-- the sign-in itself. The owner account is refused, in the database, whatever the browser asks for.

create or replace function public.cardna_delete_my_account(confirm text)
returns jsonb
language plpgsql security definer set search_path = public
as $$
declare
  uid       uuid := auth.uid();
  role_name text;
  mail      text;
begin
  if uid is null then
    return jsonb_build_object('ok', false, 'error', 'Not signed in.');
  end if;

  if lower(trim(coalesce(confirm, ''))) <> 'delete' then
    return jsonb_build_object('ok', false, 'error', 'Type delete to confirm.');
  end if;

  select lower(coalesce(p.role, 'user')) into role_name from public.profiles p where p.id = uid;
  role_name := coalesce(role_name, 'user');

  /* The owner is never deletable from the app. */
  if role_name = 'owner' then
    return jsonb_build_object('ok', false, 'error', 'The owner account cannot be deleted from the app.');
  end if;

  select lower(u.email) into mail from auth.users u where u.id = uid;

  delete from public.vehicles      where user_id = uid;
  delete from public.decode_log    where user_id = uid;
  delete from public.events        where user_id = uid;
  delete from public.vault_entries where user_id = uid;
  delete from public.profiles      where id = uid;
  if mail is not null then
    delete from public.waitlist w where lower(w.email) = mail;
  end if;
  delete from auth.users where id = uid;

  return jsonb_build_object('ok', true, 'deleted', uid::text);
end;
$$;

grant execute on function public.cardna_delete_my_account(text) to authenticated;

commit;

