-- CarDNA — F-22: the waitlist table (Turn 34)
--
-- Why: the pricing page's "join the list" panel is built and wired, but has nowhere to write.
-- This is the table, plus the two rules that keep it safe: anyone may add themselves, and nobody
-- may read the list back except staff in the console. There are no updates and no deletes from a
-- browser at all — an address on the list can only be removed by hand, on purpose.
--
-- Free to run. Nothing is emailed, and no data leaves Supabase. Idempotent: safe to run twice.
-- Run it in Supabase -> SQL Editor. assets/waitlist.js starts storing addresses the moment this
-- table exists, with no code change.

begin;

create table if not exists public.waitlist (
  id         bigint generated by default as identity primary key,
  email      text not null,
  interest   text not null default 'pro',
  source     text,
  created_at timestamptz not null default now(),
  constraint waitlist_email_len    check (char_length(email) between 5 and 180),
  constraint waitlist_interest_len check (char_length(interest) between 1 and 40)
);

-- One row per address per interest: a second "join" for the same thing is not an error,
-- it is the same person telling us twice.
create unique index if not exists waitlist_email_interest_idx
  on public.waitlist (lower(email), interest);

create index if not exists waitlist_created_idx
  on public.waitlist (created_at desc);

alter table public.waitlist enable row level security;

-- Insert-only for everyone, signed in or not: this is a mailing list, not a feature of an account.
drop policy if exists waitlist_insert on public.waitlist;
create policy waitlist_insert on public.waitlist
  for insert to anon, authenticated
  with check (true);

-- Read back only for staff, so the console can show real demand.
drop policy if exists waitlist_staff_read on public.waitlist;
create policy waitlist_staff_read on public.waitlist
  for select to authenticated
  using (public.cardna_is_staff());

grant insert on public.waitlist to anon, authenticated;
grant select on public.waitlist to authenticated;
grant usage, select on sequence public.waitlist_id_seq to anon, authenticated;

commit;

